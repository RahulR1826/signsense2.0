"""Ablation experiments for the report: what each part of the pipeline contributes.

Trains each variant with several seeds on the INCLUDE official split and writes docs/experiments.md.
Usage (from ml/): .venv/Scripts/python tools/run_experiments.py [--seeds 3] [--epochs 120]
"""

import argparse
import json
import os
import statistics
import subprocess
import sys
import time
from pathlib import Path

ML_DIR = Path(__file__).resolve().parents[1]
DOC = ML_DIR.parent / "docs" / "experiments.md"

VARIANTS = [
    ("full (CNN)", ["--model", "cnn"]),
    ("GRU instead of CNN", ["--model", "gru"]),
    ("no augmentation", ["--model", "cnn", "--no-augment"]),
    ("without face", ["--model", "cnn", "--drop", "face"]),
    ("without body pose", ["--model", "cnn", "--drop", "pose"]),
    ("without handshape features", ["--model", "cnn", "--drop", "handshape"]),
    ("hands only (no pose, no face)", ["--model", "cnn", "--drop", "pose,face"]),
]


def find_existing(args: list[str], seed: int, epochs: int) -> dict | None:
    """Reuse a finished run with the same settings (lets an interrupted experiment resume)."""
    want_model = args[args.index("--model") + 1]
    want_drop = sorted(args[args.index("--drop") + 1].split(",")) if "--drop" in args else []
    want_noaug = "--no-augment" in args
    for run_dir in sorted((ML_DIR / "runs").glob(f"*-exp-s{seed}")):
        try:
            cfg = json.loads((run_dir / "config.json").read_text(encoding="utf-8"))
            report = json.loads((run_dir / "report.json").read_text(encoding="utf-8"))
        except FileNotFoundError:
            continue
        a = cfg["args"]
        if (a["model"], sorted(cfg.get("droppedFeatures", [])), a["no_augment"], a["epochs"]) == (want_model, want_drop, want_noaug, epochs):
            return report
    return None


def run(args: list[str], tag: str) -> dict:
    # Judge success by the written report, not the exit code: on Windows, PyTorch's CUDA GRU can crash
    # during interpreter shutdown *after* everything has been saved.
    proc = subprocess.run(
        [sys.executable, "-m", "signsense_ml.train", *args, "--tag", tag],
        cwd=ML_DIR, capture_output=True, text=True, env={**os.environ, "MLFLOW_DISABLE_AGENT_HINT": "1"},
    )
    lines = [line for line in proc.stdout.splitlines() if line.startswith("run dir:")]
    if not lines:
        raise RuntimeError(f"training failed (exit {proc.returncode}):\n{proc.stderr[-2000:]}")
    run_dir = Path(lines[0].split("run dir:", 1)[1].strip())
    return json.loads((run_dir / "report.json").read_text(encoding="utf-8"))


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--seeds", type=int, default=3)
    p.add_argument("--epochs", type=int, default=120)
    a = p.parse_args()

    rows = []
    for name, args in VARIANTS:
        accs, f1s, top3s, params = [], [], [], 0
        for seed in range(a.seeds):
            t0 = time.time()
            r = find_existing(args, seed, a.epochs) or run([*args, "--epochs", str(a.epochs), "--seed", str(seed)], tag=f"exp-s{seed}")
            accs.append(r["test"]["accuracy"])
            f1s.append(r["test"]["macro_f1"])
            top3s.append(r["test"]["top3_accuracy"])
            params = r["params"]
            print(f"{name:32} seed {seed}: acc {accs[-1]:.3f}  ({time.time() - t0:.0f}s)", flush=True)
        rows.append((name, accs, f1s, top3s, params))

    def fmt(xs: list[float]) -> str:
        return f"{statistics.mean(xs) * 100:.1f} ± {statistics.pstdev(xs) * 100:.1f}" if len(xs) > 1 else f"{xs[0] * 100:.1f}"

    lines = [
        "# Experiments — isolated ISL sign recognition (39 signs)",
        "",
        f"INCLUDE official split (train 533 / val 54 / test 121 clips), {a.epochs} epochs, mean ± std over {a.seeds} seeds.",
        "Generated by `ml/tools/run_experiments.py`.",
        "",
        "**Caveat:** INCLUDE does not publish signer identities and its split is not documented as",
        "signer-independent, so the test set likely shares signers with training: these numbers measure",
        "generalisation to new recordings of (probably) known signers, not to new people. One test clip = 0.83",
        "points, so differences under ~2 points are within noise. Real-world accuracy on unseen signers must be",
        "measured separately (own recordings, `own` split).",
        "",
        "| Variant | Test accuracy % | Macro-F1 % | Top-3 % | Params |",
        "|---|---|---|---|---|",
    ]
    for name, accs, f1s, top3s, params in rows:
        lines.append(f"| {name} | {fmt(accs)} | {fmt(f1s)} | {fmt(top3s)} | {params:,} |")
    lines.append("")
    DOC.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
